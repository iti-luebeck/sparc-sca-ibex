#!/usr/bin/env python3
"""
3x3 Matrix-Vector Multiplication Scenario Generator for Ibex CellIFT

Generates test cases with fixed weight matrix (tainted) and 
random input vectors to observe taint propagation through multiplication.

Generates:
1. input_N.h - Header files with random input data for each test case
2. Updates main.S with the current input vector
3. Builds executables for each input configuration

Operation: output = weights * input (3x3 matrix times 3x1 vector)
- Fixed weights (tainted): 9 bytes (3x3 uint8_t matrix)
- Variable inputs: 3 x uint8_t per test case

Usage:
    python3 generate_scenario.py -n 10                    # Generate 10 input sets
    python3 generate_scenario.py -n 10 --build            # Generate and build all
    python3 generate_scenario.py -n 10 --seed 42          # Reproducible generation
    python3 generate_scenario.py -n 10 --build --run      # Generate, build, and run
"""

import argparse
import os
import sys
import subprocess
import random
from datetime import datetime
from pathlib import Path


# Matrix dimensions (must match tinyai.c)
SIZE = 3


def generate_random_inputs(size=SIZE, value_range=(0, 255)):
    """
    Generate random input vector with uint8_t values.
    
    Returns:
        List of size uint8_t values (0-255)
    """
    inputs = []
    for _ in range(size):
        val = random.randint(value_range[0], value_range[1])
        inputs.append(val)
    return inputs


def inputs_to_hex_string(inputs):
    """Convert input vector to hex string for display."""
    vals = ", ".join([f"{v:3d}" for v in inputs])
    return f"  Input vector: [{vals}]"


def generate_input_header(inputs, index):
    """Generate a C header file with input data."""
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    
    vals = ", ".join([f"{v:3d}" for v in inputs])
    
    header = f'''/**
 * 3x3 Matrix-Vector Input Data - Test Case {index}
 * Auto-generated by generate_scenario.py at {timestamp}
 * 
 * Operation: output = weights * input (3x3 matrix times 3x1 vector)
 * Format: uint8_t (0-255)
 */

#ifndef INPUT_{index}_H
#define INPUT_{index}_H

#include <stdint.h>

#define SIZE {SIZE}

/* Input vector: {SIZE} x uint8_t */
static const uint8_t test_input[SIZE] = {{ {vals} }};

#endif /* INPUT_{index}_H */
'''
    
    return header


def generate_input_asm(inputs, index):
    """Generate assembly snippet for input data."""
    vals = ", ".join([f"{v:3d}" for v in inputs])
    lines = []
    lines.append(f"/* Input data for test case {index} */")
    lines.append("  .globl input_vec")
    lines.append("input_vec:")
    lines.append(f"    .byte  {vals}")
    return "\n".join(lines)


def update_main_asm(inputs, index, template_path, output_path):
    """Update main.S with new input data."""
    with open(template_path, 'r') as f:
        content = f.read()
    
    # Find and replace the input_vec section
    import re
    
    # Pattern to match the input_vec data section
    # Match from "input_vec:" to the next .align (with possible whitespace/newlines)
    pattern = r'(\.globl input_vec\ninput_vec:\n)(.*?)(\n\n  \.align)'
    
    # New input data - single .byte directive
    vals = ", ".join([f"{v:3d}" for v in inputs])
    new_inputs = f"    .byte  {vals}    /* test case {index} */\n"
    
    replacement = r'\1' + new_inputs + r'\3'
    
    new_content = re.sub(pattern, replacement, content, flags=re.DOTALL)
    
    # Verify the replacement worked
    if new_content == content:
        print(f"WARNING: main.S replacement for test case {index} did not change the file!")
        print("  Check the input_vec section format in main.S.orig")
    
    with open(output_path, 'w') as f:
        f.write(new_content)


def generate_test_cases(num_cases, seed=None):
    """Generate all test cases with random inputs."""
    if seed is not None:
        random.seed(seed)
    
    cases = []
    for i in range(num_cases):
        inputs = generate_random_inputs()
        cases.append(inputs)
    
    return cases


def main():
    parser = argparse.ArgumentParser(
        description="Generate 3x3 matrix-vector multiplication scenarios for Ibex CellIFT",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Generate 10 test cases
  %(prog)s -n 10

  # Generate with seed for reproducibility
  %(prog)s -n 20 --seed 42

  # Generate and build all executables
  %(prog)s -n 10 --build

  # Generate, build, and show run commands
  %(prog)s -n 10 --build --verbose
"""
    )
    
    parser.add_argument(
        "-n", "--num-cases",
        type=int,
        required=True,
        help="Number of test cases (input variations) to generate"
    )
    
    parser.add_argument(
        "--seed",
        type=int,
        default=None,
        help="Random seed for reproducible generation"
    )
    
    parser.add_argument(
        "--build",
        action="store_true",
        help="Build all executables after generating"
    )
    
    parser.add_argument(
        "--value-range",
        type=int,
        nargs=2,
        default=[0, 255],
        metavar=("MIN", "MAX"),
        help="Range for random input values (default: 0 255)"
    )
    
    parser.add_argument(
        "--gen-run-script",
        action="store_true",
        help="Generate run_all_simulations.sh script"
    )
    
    parser.add_argument(
        "--verbose", "-v",
        action="store_true",
        help="Show verbose output"
    )
    
    args = parser.parse_args()
    
    # Get script directory
    script_dir = Path(__file__).parent
    build_dir = script_dir / "build"
    
    print("=" * 60)
    print("3x3 Matrix-Vector Scenario Generator for Ibex CellIFT")
    print("=" * 60)
    print(f"Number of test cases: {args.num_cases}")
    print(f"Input range: [{args.value_range[0]}, {args.value_range[1]}] (uint8_t)")
    print(f"Operation: output = weights * input (3x3 @ 3x1)")
    print(f"Random seed: {args.seed if args.seed else 'None (random)'}")
    print()
    
    # Set random seed
    if args.seed is not None:
        random.seed(args.seed)
    
    # Generate test cases
    print("Generating input test cases...")
    cases = []
    for i in range(args.num_cases):
        inputs = generate_random_inputs(value_range=tuple(args.value_range))
        cases.append(inputs)
        
        # Write individual header file
        header = generate_input_header(inputs, i)
        header_path = script_dir / f"input_{i}.h"
        with open(header_path, 'w') as f:
            f.write(header)
    
    print(f"  Created {args.num_cases} input header files (input_0.h ... input_{args.num_cases-1}.h)")
    
    # Show sample
    print()
    print("Sample (first test case):")
    print(inputs_to_hex_string(cases[0]))
    
    # Create build directory
    build_dir.mkdir(exist_ok=True)
    
    # Build if requested
    if args.build:
        print()
        print("Building executables...")
        
        # Save original main.S
        main_asm_path = script_dir / "main.S"
        main_asm_backup = script_dir / "main.S.orig"
        
        if not main_asm_backup.exists():
            subprocess.run(["cp", str(main_asm_path), str(main_asm_backup)])
        
        success_count = 0
        fail_count = 0
        
        for i, inputs in enumerate(cases):
            # Update main.S with this test case's inputs
            update_main_asm(inputs, i, main_asm_backup, main_asm_path)
            
            # Clean and build (remove only the app.elf to force rebuild)
            app_elf = script_dir / "build" / "app.elf"
            if app_elf.exists():
                app_elf.unlink()
            
            result = subprocess.run(
                ["make"],
                cwd=script_dir,
                capture_output=True,
                text=True
            )
            
            if result.returncode == 0:
                # Copy to numbered output
                src = script_dir / "build" / "app.elf"
                dst = build_dir / f"app_{i}.elf"
                subprocess.run(["cp", str(src), str(dst)])
                
                # Also copy the dump file
                src_dump = script_dir / "build" / "app.elf.dump"
                dst_dump = build_dir / f"app_{i}.elf.dump"
                if src_dump.exists():
                    subprocess.run(["cp", str(src_dump), str(dst_dump)])
                
                success_count += 1
                if args.verbose:
                    print(f"  Built app_{i}.elf")
            else:
                fail_count += 1
                print(f"  FAILED: app_{i}.elf")
                if args.verbose:
                    print(result.stderr)
        
        # Restore original main.S
        subprocess.run(["cp", str(main_asm_backup), str(main_asm_path)])
        
        print(f"  Built {success_count}/{args.num_cases} executables")
        if fail_count > 0:
            print(f"  {fail_count} builds failed")
        
        # Show sizes
        print()
        print("Build output:")
        subprocess.run(["ls", "-lh", str(build_dir)], capture_output=False)
    
    # Generate run script (only if --gen-run-script flag is set)
    if args.gen_run_script:
        run_script = generate_run_script(args.num_cases, script_dir)
        run_script_path = script_dir / "run_all_simulations.sh"
        with open(run_script_path, 'w') as f:
            f.write(run_script)
        os.chmod(run_script_path, 0o755)
        print()
        print(f"Created run script: {run_script_path}")
    
    print()
    print("=" * 60)
    print("Next steps:")
    print("=" * 60)
    if not args.build:
        print(f"  1. Build executables:  python3 generate_scenario.py -n {args.num_cases} --build")
    print(f"  2. Run all sims:       ./run_all_simulations.sh")
    print(f"  3. Run single sim:     ./run_all_simulations.sh --single 5")
    print(f"  4. Run CellIFT:        ./run_all_simulations.sh --cellift")
    print(f"  5. Analyze traces:     python3 ../../scripts/analyze_taint_propagation.py traces/cellift_0.vcd")
    print()
    
    return 0


def generate_run_script(num_cases, script_dir):
    """Generate the run_all_simulations.sh script."""
    cellift_dir = script_dir.parent.parent  # sw/scenario -> cellift
    
    return f'''#!/bin/bash
#
# Run all 3x3 matrix-vector simulations for Ibex CellIFT
# Auto-generated by generate_scenario.py
#
# Usage:
#   ./run_all_simulations.sh                    # Run all vanilla sims
#   ./run_all_simulations.sh --cellift          # Run all CellIFT sims
#   ./run_all_simulations.sh --single 5         # Run only test case 5
#   ./run_all_simulations.sh --range 0 9        # Run test cases 0-9
#   ./run_all_simulations.sh --simlen 5000      # Custom cycle count
#   ./run_all_simulations.sh --jobs 4           # Run 4 sims in parallel

set -e

# Get script directory
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
CELLIFT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"

# Configuration
NUM_CASES={num_cases}
SIMLEN=1000
TRACE_DIR="$SCRIPT_DIR/traces"
BUILD_DIR="$SCRIPT_DIR/build"
MAX_JOBS=$(nproc 2>/dev/null || echo 4)

# Simulator paths
VANILLA_SIM="$CELLIFT_DIR/build/run_vanilla_trace_0.1/default-verilator/Vibex_tiny_soc"
CELLIFT_SIM="$CELLIFT_DIR/build/run_cellift_trace_0.1/default-verilator/Vibex_tiny_soc"

# Taint configuration (fixed for all runs - the weights)
TAINT_FILE="$CELLIFT_DIR/taint_data/scenario_tinyai_tainted_weights/taint_data.txt"

# Colors
RED='\\033[0;31m'
GREEN='\\033[0;32m'
YELLOW='\\033[1;33m'
BLUE='\\033[0;34m'
NC='\\033[0m'

# Temp directory for job status
STATUS_DIR=$(mktemp -d)
trap "rm -rf $STATUS_DIR" EXIT

mkdir -p "$TRACE_DIR"

# Run a single simulation
run_sim() {{
    local idx=$1
    local sim_type=$2
    
    local sim_bin="$VANILLA_SIM"
    local trace_ext="vcd"
    local taint_arg=""
    
    if [ "$sim_type" = "cellift" ]; then
        sim_bin="$CELLIFT_SIM"
        trace_ext="vcd"  # Use VCD, not FST (FST is extremely slow with CellIFT)
        taint_arg="$TAINT_FILE"
    fi
    
    local elf_file="$BUILD_DIR/app_${{idx}}.elf"
    local trace_file="$TRACE_DIR/${{sim_type}}_${{idx}}.${{trace_ext}}"
    local status_file="$STATUS_DIR/status_${{idx}}"
    
    if [ ! -f "$elf_file" ]; then
        echo "FAIL:ELF not found: $elf_file" > "$status_file"
        return 1
    fi
    
    if [ ! -f "$sim_bin" ]; then
        echo "FAIL:Simulator not found: $sim_bin" > "$status_file"
        return 1
    fi
    
    # Run simulation
    SIMSRAMELF="$elf_file" \\
    SIMROMELF="$elf_file" \\
    TRACEFILE="$trace_file" \\
    SIMLEN="$SIMLEN" \\
    SIMSRAMTAINT="${{taint_arg:-/dev/null}}" \\
    SIMROMTAINT="${{taint_arg:-/dev/null}}" \\
    "$sim_bin" > /dev/null 2>&1
    
    if [ -f "$trace_file" ]; then
        local size=$(du -h "$trace_file" | cut -f1)
        echo "OK:$size" > "$status_file"
        return 0
    else
        echo "FAIL:No trace generated" > "$status_file"
        return 1
    fi
}}

export -f run_sim
export VANILLA_SIM CELLIFT_SIM BUILD_DIR TRACE_DIR SIMLEN STATUS_DIR TAINT_FILE

# Parse arguments
SIM_TYPE="vanilla"
START_IDX=0
END_IDX=$((NUM_CASES - 1))
DRY_RUN=false

while [[ $# -gt 0 ]]; do
    case $1 in
        --cellift) SIM_TYPE="cellift"; shift ;;
        --vanilla) SIM_TYPE="vanilla"; shift ;;
        --range) START_IDX=$2; END_IDX=$3; shift 3 ;;
        --single) START_IDX=$2; END_IDX=$2; shift 2 ;;
        --simlen) SIMLEN=$2; shift 2 ;;
        --jobs) MAX_JOBS=$2; shift 2 ;;
        --dry-run) DRY_RUN=true; shift ;;
        --help)
            echo "Usage: $0 [OPTIONS]"
            echo ""
            echo "Options:"
            echo "  --vanilla       Run vanilla simulations (default)"
            echo "  --cellift       Run CellIFT simulations with taint tracking"
            echo "  --single N      Run only test case N"
            echo "  --range A B     Run test cases A through B"
            echo "  --simlen N      Set simulation length (default: 3000)"
            echo "  --jobs N        Run N simulations in parallel (default: nproc)"
            echo "  --dry-run       Show what would be run without executing"
            echo "  --help          Show this help"
            exit 0
            ;;
        *) echo "Unknown option: $1"; exit 1 ;;
    esac
done

# Validate indices
if [ $START_IDX -lt 0 ] || [ $END_IDX -ge $NUM_CASES ]; then
    echo -e "${{RED}}Error: Index out of range (0-$((NUM_CASES-1)))${{NC}}"
    exit 1
fi

NUM_TO_RUN=$((END_IDX - START_IDX + 1))

echo -e "${{BLUE}}=======================================${{NC}}"
echo -e "${{BLUE}}3x3 Matrix-Vector Simulation Runner${{NC}}"
echo -e "${{BLUE}}=======================================${{NC}}"
echo ""
echo "Mode:           $SIM_TYPE"
echo "Test cases:     $START_IDX to $END_IDX ($NUM_TO_RUN total)"
echo "Simulation len: $SIMLEN cycles"
echo "Max parallel:   $MAX_JOBS"
echo "Trace output:   $TRACE_DIR"
echo ""

if [ "$DRY_RUN" = true ]; then
    echo -e "${{YELLOW}}DRY RUN - showing commands:${{NC}}"
    for ((i=START_IDX; i<=END_IDX; i++)); do
        echo "  run_sim $i $SIM_TYPE"
    done
    exit 0
fi

# Check for simulators
if [ "$SIM_TYPE" = "vanilla" ] && [ ! -f "$VANILLA_SIM" ]; then
    echo -e "${{RED}}Error: Vanilla simulator not found at:${{NC}}"
    echo "  $VANILLA_SIM"
    echo ""
    echo "Build with:  cd $CELLIFT_DIR && make run_vanilla_trace"
    exit 1
fi

if [ "$SIM_TYPE" = "cellift" ] && [ ! -f "$CELLIFT_SIM" ]; then
    echo -e "${{RED}}Error: CellIFT simulator not found at:${{NC}}"
    echo "  $CELLIFT_SIM"
    echo ""
    echo "Build with:  cd $CELLIFT_DIR && make run_cellift_trace"
    exit 1
fi

# Run simulations
echo "Starting simulations..."
START_TIME=$(date +%s)

# Sequential or parallel
if [ $NUM_TO_RUN -eq 1 ]; then
    # Single run - show output
    run_sim $START_IDX $SIM_TYPE
    result=$(cat "$STATUS_DIR/status_$START_IDX" 2>/dev/null || echo "FAIL:Unknown")
    if [[ "$result" == OK:* ]]; then
        size="${{result#OK:}}"
        echo -e "${{GREEN}}[PASS]${{NC}} Test case $START_IDX ($size)"
    else
        reason="${{result#FAIL:}}"
        echo -e "${{RED}}[FAIL]${{NC}} Test case $START_IDX: $reason"
    fi
else
    # Parallel runs
    for ((i=START_IDX; i<=END_IDX; i++)); do
        run_sim $i $SIM_TYPE &
        
        # Limit parallel jobs
        if [ $(jobs -r | wc -l) -ge $MAX_JOBS ]; then
            wait -n 2>/dev/null || wait
        fi
    done
    wait
    
    # Collect results
    success=0
    fail=0
    for ((i=START_IDX; i<=END_IDX; i++)); do
        result=$(cat "$STATUS_DIR/status_$i" 2>/dev/null || echo "FAIL:Unknown")
        if [[ "$result" == OK:* ]]; then
            ((success++)) || true
        else
            ((fail++)) || true
            reason="${{result#FAIL:}}"
            echo -e "${{RED}}[FAIL]${{NC}} Test case $i: $reason"
        fi
    done
    
    END_TIME=$(date +%s)
    ELAPSED=$((END_TIME - START_TIME))
    
    echo ""
    echo -e "${{GREEN}}Completed: $success/$NUM_TO_RUN successful${{NC}}"
    if [ $fail -gt 0 ]; then
        echo -e "${{RED}}Failed:    $fail${{NC}}"
    fi
    echo "Time:       ${{ELAPSED}}s"
fi

echo ""
echo "Traces saved to: $TRACE_DIR"
echo ""
echo "To analyze taint propagation:"
echo "  python3 $CELLIFT_DIR/../cellift-chipyard/cellift-rocket/scripts/analyze_taint_propagation.py $TRACE_DIR/cellift_0.vcd"
'''


if __name__ == "__main__":
    sys.exit(main())
